// Agentic AI Multi-Agent Orchestration Pipeline

export const FIELD_DEFINITIONS = {
  BRKAGE_RATE: "Brokerage rate (in % or BPS) applicable to the transaction or asset under management calculation.",
  BRKAGE_AMT: "Total gross brokerage commission amount generated by this transaction or holding.",
  AVG_ASSETS: "Average asset value under advisory used as the calculation base for trail commission.",
  AM_RATE: "Rate associated with the AM component in the source data.",
  CAM_RATE: "Rate associated with the CAM component in the source data.",
  MAM_RATE: "Rate associated with the MAM component in the source data.",
  AM_COMM: "Meaning could not be determined from the uploaded document.",
  CAM_COMM: "Meaning could not be determined from the uploaded document.",
  MAM_COMM: "Meaning could not be determined from the uploaded document.",
  TDS_DEDUCTED: "Tax deducted at source amount reported in the source data.",
  GST_AMT: "GST amount reported in the source data.",
  UNITS: "Number of mutual fund units allotted or held under the specific folio.",
  NAV: "Net Asset Value per unit on the transaction or valuation date.",
  CURR_VAL: "Current value reported in the source data.",
  XIRR: "Extended Internal Rate of Return (annualized compound return taking dated cashflows into account).",
};

const hasValue = (value) => value !== null && value !== undefined && String(value).trim() !== '';
const hasNumericValue = (value) => hasValue(value) && Number.isFinite(Number(value));

export class AgenticPipeline {
  constructor() {
    this.agents = [
      { id: "classification", name: "Document Classification Agent", role: "Identifies document type, source, and layout schema." },
      { id: "extraction", name: "Document Extraction Agent", role: "Extracts textual & tabular records from file streams." },
      { id: "normalization", name: "Normalization Agent", role: "Maps source columns into normalized internal representation." },
      { id: "brokerage", name: "Brokerage Analysis Agent", role: "Calculates commission tiers, trail bps, GST, and TDS." },
      { id: "mutualfund", name: "Mutual Fund Analysis Agent", role: "Categorizes schemes, units, AMCs, and portfolio allocation." },
      { id: "return", name: "Return Analysis Agent", role: "Computes deterministic XIRR/CAGR when valuation data is present." },
      { id: "bi", name: "Business Intelligence Agent", role: "Detects concentration, anomalies, and missing data gaps." },
      { id: "recommendation", name: "Recommendation Agent", role: "Generates data-backed observations and monitoring triggers." },
      { id: "report", name: "Report Generation Agent", role: "Compiles 10-section executive summary & audit reports." },
      { id: "qa", name: "Question Answering Agent", role: "Answers natural language queries strictly using document facts." }
    ];
  }

  // Multi-Agent Execution Pipeline with step-by-step telemetry
  async processDocument(rawDoc, onAgentStep) {
    const logs = [];
    const pushLog = (agentName, status, detail) => {
      const entry = { agent: agentName, status, detail, timestamp: new Date().toLocaleTimeString() };
      logs.push(entry);
      if (onAgentStep) onAgentStep(entry, logs);
    };

    // Step 1: Document Classification Agent
    pushLog("Document Classification Agent", "RUNNING", `Analyzing structure of ${rawDoc.name}...`);
    await new Promise((r) => setTimeout(r, 400));
    const detectedSource = rawDoc.source || "Source not identified";
    const detectedType = rawDoc.docType || "Document type not identified";
    pushLog("Document Classification Agent", "COMPLETED", `Detected: Source=${detectedSource}, Format=${rawDoc.name.split('.').pop().toUpperCase()}`);

    // Step 2: Document Extraction Agent
    pushLog("Document Extraction Agent", "RUNNING", "Parsing tabular fields, metadata, and raw rows...");
    await new Promise((r) => setTimeout(r, 450));
    const rawRecords = rawDoc.records || [];
    pushLog("Document Extraction Agent", "COMPLETED", `Extracted ${rawRecords.length} records and ${rawDoc.rawColumns?.length || 0} source columns.`);

    // Step 3: Normalization Agent
    pushLog("Normalization Agent", "RUNNING", "Mapping technical columns (BRKAGE_RATE, AVG_ASSETS, CAM_RATE) to normalized schema...");
    await new Promise((r) => setTimeout(r, 400));
    const normalizedRecords = rawRecords.map((r) => ({
      ...r,
      fieldGlossary: {
        BRKAGE_RATE: hasValue(r.brokerageRate) ? `${r.brokerageRate} -> ${FIELD_DEFINITIONS.BRKAGE_RATE}` : "Not present in record",
        BRKAGE_AMT: hasNumericValue(r.brokerageAmount) ? `₹${r.brokerageAmount} -> ${FIELD_DEFINITIONS.BRKAGE_AMT}` : "Not present in record",
        AVG_ASSETS: hasNumericValue(r.averageAssets) ? `₹${r.averageAssets} -> ${FIELD_DEFINITIONS.AVG_ASSETS}` : "Not present in record",
        AM_RATE: hasValue(r.amRate) ? `${r.amRate} -> ${FIELD_DEFINITIONS.AM_RATE}` : "Meaning could not be determined from the uploaded document.",
        CAM_RATE: hasValue(r.camRate) ? `${r.camRate} -> ${FIELD_DEFINITIONS.CAM_RATE}` : "Meaning could not be determined from the uploaded document.",
        MAM_RATE: hasValue(r.mamRate) ? `${r.mamRate} -> ${FIELD_DEFINITIONS.MAM_RATE}` : "Meaning could not be determined from the uploaded document.",
        AM_COMM: hasValue(r.amComm) ? FIELD_DEFINITIONS.AM_COMM : "Not present in record",
        CAM_COMM: hasValue(r.camComm) ? FIELD_DEFINITIONS.CAM_COMM : "Not present in record",
        MAM_COMM: hasValue(r.mamComm) ? FIELD_DEFINITIONS.MAM_COMM : "Not present in record",
      }
    }));
    pushLog("Normalization Agent", "COMPLETED", "All source columns mapped to internal schema with plain English definitions.");

    // Step 4: Brokerage Analysis Agent
    pushLog("Brokerage Analysis Agent", "RUNNING", "Aggregating trail commissions, gross brokerage, and AMC payouts...");
    await new Promise((r) => setTimeout(r, 450));
    const brokerageIsComplete = normalizedRecords.length > 0 && normalizedRecords.every((record) => hasNumericValue(record.brokerageAmount));
    const assetsAreComplete = normalizedRecords.length > 0 && normalizedRecords.every((record) => hasNumericValue(record.averageAssets));
    const totalBrokerage = brokerageIsComplete
      ? normalizedRecords.reduce((sum, r) => sum + Number(r.brokerageAmount), 0)
      : null;
    const totalAssets = assetsAreComplete
      ? normalizedRecords.reduce((sum, r) => sum + Number(r.averageAssets), 0)
      : null;
    const rateValues = normalizedRecords
      .map((record) => {
        const match = String(record.brokerageRate ?? '').trim().match(/^(-?\d+(?:\.\d+)?)\s*(%|BPS)$/i);
        if (!match) return null;
        const value = Number(match[1]);
        return match[2].toUpperCase() === 'BPS' ? value / 100 : value;
      })
      .filter((value) => value !== null && Number.isFinite(value));
    const avgBrokerageRate = rateValues.length === normalizedRecords.length && rateValues.length > 0
      ? `${(rateValues.reduce((sum, value) => sum + value, 0) / rateValues.length).toFixed(2)}%`
      : "Not available";
    pushLog("Brokerage Analysis Agent", "COMPLETED", `Total Brokerage: ${totalBrokerage === null ? "Not available" : `₹${totalBrokerage.toLocaleString('en-IN')}`}, Average Rate: ${avgBrokerageRate}`);

    // Step 5: Mutual Fund Analysis Agent
    pushLog("Mutual Fund Analysis Agent", "RUNNING", "Analyzing scheme concentration, category allocation, and unit balances...");
    await new Promise((r) => setTimeout(r, 400));
    const schemeMap = {};
    normalizedRecords.forEach((r) => {
      const name = r.schemeName || "Scheme not identified";
      if (!schemeMap[name]) {
        schemeMap[name] = {
          schemeName: name,
          amcCode: r.amcCode || null,
          category: r.category || null,
          totalInvestment: 0,
          totalUnits: 0,
          currentValue: 0,
          totalInvested: 0,
          brokerageAmount: 0,
          recordsCount: 0,
          investmentComplete: true,
          unitsComplete: true,
          currentValueComplete: true,
          investedTotalComplete: true,
          brokerageComplete: true,
          xirr: r.xirr ?? null,
        };
      }
      const scheme = schemeMap[name];
      if (hasNumericValue(r.investmentAmount)) scheme.totalInvestment += Number(r.investmentAmount);
      else scheme.investmentComplete = false;
      if (hasNumericValue(r.units)) scheme.totalUnits += Number(r.units);
      else scheme.unitsComplete = false;
      if (hasNumericValue(r.currentValue)) scheme.currentValue += Number(r.currentValue);
      else scheme.currentValueComplete = false;
      if (hasNumericValue(r.investedTotal)) scheme.totalInvested += Number(r.investedTotal);
      else scheme.investedTotalComplete = false;
      if (hasNumericValue(r.brokerageAmount)) scheme.brokerageAmount += Number(r.brokerageAmount);
      else scheme.brokerageComplete = false;
      schemeMap[name].recordsCount += 1;
    });
    const schemeList = Object.values(schemeMap).map((scheme) => ({
      ...scheme,
      totalInvestment: scheme.investmentComplete ? scheme.totalInvestment : null,
      totalUnits: scheme.unitsComplete ? scheme.totalUnits : null,
      currentValue: scheme.currentValueComplete ? scheme.currentValue : null,
      totalInvested: scheme.investedTotalComplete ? scheme.totalInvested : null,
      brokerageAmount: scheme.brokerageComplete ? scheme.brokerageAmount : null,
    }));
    pushLog("Mutual Fund Analysis Agent", "COMPLETED", `Identified ${schemeList.length} unique mutual fund schemes across ${normalizedRecords.length} transactions.`);

    // Step 6: Return Analysis Agent (Deterministic with zero hallucination)
    pushLog("Return Analysis Agent", "RUNNING", "Evaluating return availability (Invested Amount, NAV, Current Value, XIRR)...");
    await new Promise((r) => setTimeout(r, 400));
    const returnPositionKeys = normalizedRecords.map((record) => `${record.folioNumber ?? ''}\u0000${record.schemeCode ?? record.schemeName ?? ''}`);
    const hasUniqueReturnPositions = returnPositionKeys.every((key) => !key.startsWith('\u0000') && !key.endsWith('\u0000')) &&
      new Set(returnPositionKeys).size === returnPositionKeys.length;
    const hasSufficientValuation = normalizedRecords.length > 0 && hasUniqueReturnPositions &&
      normalizedRecords.every((record) =>
        hasNumericValue(record.currentValue) &&
        hasNumericValue(record.investedTotal) &&
        Number(record.investedTotal) > 0
      );
    
    let returnAnalysisResult;
    if (hasSufficientValuation) {
      const totalInvested = normalizedRecords.reduce((sum, r) => sum + Number(r.investedTotal), 0);
      const totalCurrentVal = normalizedRecords.reduce((sum, r) => sum + Number(r.currentValue), 0);
      const totalProfit = totalCurrentVal - totalInvested;
      const absoluteReturn = totalInvested > 0 ? ((totalProfit / totalInvested) * 100).toFixed(2) : 0;
      
      returnAnalysisResult = {
        hasSufficientData: true,
        totalInvested,
        totalCurrentVal,
        totalProfit,
        absoluteReturn: parseFloat(absoluteReturn),
        avgXIRR: null,
        calculationBasis: "Invested Amount = Sum of purchases; Current Value = Units × Latest NAV; Profit = Current Value - Invested Amount; Return % = (Profit / Invested Amount) × 100",
        message: "Returns calculated deterministically from documented purchase cost and recorded NAV values."
      };
      pushLog("Return Analysis Agent", "COMPLETED", `Computed Absolute Return: +${absoluteReturn}% (Profit: ₹${totalProfit.toLocaleString('en-IN')})`);
    } else {
      returnAnalysisResult = {
        hasSufficientData: false,
        totalInvested: normalizedRecords.reduce((sum, r) => sum + (r.investmentAmount || 0), 0),
        totalCurrentVal: null,
        totalProfit: null,
        absoluteReturn: null,
        avgXIRR: null,
        calculationBasis: null,
        message: "Return cannot be calculated reliably from this document alone because current valuation/NAV information is missing."
      };
      pushLog("Return Analysis Agent", "WARNING", "Valuation/NAV fields missing in document. Suppressed return calculation as per strict financial compliance.");
    }

    // Step 7: Business Intelligence Agent
    pushLog("Business Intelligence Agent", "RUNNING", "Scanning for portfolio patterns, fee drivers, and concentration anomalies...");
    await new Promise((r) => setTimeout(r, 450));
    const topSchemeByInv = [...schemeList].filter((scheme) => scheme.totalInvestment !== null).sort((a, b) => b.totalInvestment - a.totalInvestment)[0];
    const topSchemeByBrk = [...schemeList].filter((scheme) => scheme.brokerageAmount !== null).sort((a, b) => b.brokerageAmount - a.brokerageAmount)[0];
    
    const biInsights = [];
    if (topSchemeByInv && topSchemeByInv.totalInvestment > 0) {
      biInsights.push({
        title: "Largest Investment",
        detail: `Based on the uploaded data, ${topSchemeByInv.schemeName} has the largest recorded investment at ₹${topSchemeByInv.totalInvestment.toLocaleString('en-IN')}.`,
        type: "CONCENTRATION"
      });
    }
    if (topSchemeByBrk && topSchemeByBrk.brokerageAmount > 0) {
      biInsights.push({
        title: "Largest Brokerage Contributor",
        detail: `Based on the uploaded data, ${topSchemeByBrk.schemeName} has the largest recorded brokerage amount at ₹${topSchemeByBrk.brokerageAmount.toLocaleString('en-IN')}.`,
        type: "REVENUE"
      });
    }
    if (!hasSufficientValuation) {
      biInsights.push({
        title: "Return Data Availability",
        detail: "Current valuation and invested-value data are incomplete. Additional NAV/valuation data is required before determining actual returns.",
        type: "MISSING_DATA"
      });
    }
    pushLog("Business Intelligence Agent", "COMPLETED", `Generated ${biInsights.length} data-grounded business intelligence findings.`);

    // Step 8: Recommendation Agent (Strictly data-backed)
    pushLog("Recommendation Agent", "RUNNING", "Formulating objective, non-predictive observation checkpoints...");
    await new Promise((r) => setTimeout(r, 400));
    const recommendations = [];
    if (topSchemeByInv && topSchemeByInv.totalInvestment > 0) {
      recommendations.push({
        tag: "Investment Concentration",
        observation: `Based on the uploaded data, ${topSchemeByInv.schemeName} has the highest recorded investment. This may be worth reviewing alongside the investor's objectives and risk profile.`,
        action: "Review the largest holding against the investor's stated objectives"
      });
    }
    if (!hasSufficientValuation) {
      recommendations.push({
        tag: "Missing Valuation Resolution",
        observation: "Additional NAV/valuation data is required before determining actual investor return percentage.",
        action: "Upload supplemental CAS or CAMS WBR2 valuation statement"
      });
    }
    pushLog("Recommendation Agent", "COMPLETED", `Formulated ${recommendations.length} data-supported recommendations.`);

    // Step 9: Report Generation Agent
    pushLog("Report Generation Agent", "RUNNING", "Compiling 10-section formal executive summary report...");
    await new Promise((r) => setTimeout(r, 450));
    const fullReport = {
      docId: rawDoc.id,
      docName: rawDoc.name,
      source: detectedSource,
      docType: detectedType,
      processedAt: new Date().toISOString(),
      summary: {
        totalRecords: normalizedRecords.length,
        totalInvestment: normalizedRecords.length > 0 && normalizedRecords.every((record) => hasNumericValue(record.investmentAmount))
          ? normalizedRecords.reduce((sum, record) => sum + Number(record.investmentAmount), 0)
          : null,
        totalUnits: normalizedRecords.length > 0 && normalizedRecords.every((record) => hasNumericValue(record.units))
          ? normalizedRecords.reduce((sum, record) => sum + Number(record.units), 0)
          : null,
        totalBrokerage,
        avgBrokerageRate,
        totalAssetsAnalyzed: totalAssets,
        schemesCount: schemeList.length,
        foliosCount: new Set(normalizedRecords.map((record) => record.folioNumber).filter(hasValue)).size || null,
        investorsCount: new Set(normalizedRecords.map((record) => record.investorName).filter(hasValue)).size || null,
        period: rawDoc.period || "Not available"
      },
      normalizedRecords,
      schemeList,
      returnAnalysis: returnAnalysisResult,
      biInsights,
      recommendations,
      missingDataFields: [
        ['Investment amount', (record) => hasNumericValue(record.investmentAmount)],
        ['Units', (record) => hasNumericValue(record.units)],
        ['Brokerage amount', (record) => hasNumericValue(record.brokerageAmount)],
        ['Brokerage rate', (record) => hasValue(record.brokerageRate)],
        ['Average assets', (record) => hasNumericValue(record.averageAssets)],
        ['Current value', (record) => hasNumericValue(record.currentValue)],
        ['Invested total', (record) => hasNumericValue(record.investedTotal)],
      ].filter(([, isPresent]) => !normalizedRecords.length || normalizedRecords.some((record) => !isPresent(record)))
        .map(([field]) => field),
      suggestedQuestions: this.generateDynamicQuestions(rawDoc, schemeList, hasSufficientValuation, totalBrokerage)
    };
    pushLog("Report Generation Agent", "COMPLETED", "10-Section comprehensive report successfully synthesized and cached.");

    // Step 10: Question Answering Agent Ready
    pushLog("Question Answering Agent", "READY", "Chatbot contextualized with extracted document facts and field dictionary.");

    return {
      success: true,
      report: fullReport,
      logs
    };
  }

  // Generates dynamic suggested questions tailored to the uploaded document
  generateDynamicQuestions(doc, schemeList, hasValuation, totalBrokerage) {
    const topScheme = schemeList[0]?.schemeName || "top scheme";
    const brokerageSummary = totalBrokerage != null && Number.isFinite(Number(totalBrokerage))
      ? `Total brokerage recorded is ₹${Number(totalBrokerage).toLocaleString('en-IN')}.`
      : 'Brokerage totals are not available in this document.';
    const questions = [
      "What is my total investment and total units in this document?",
      `How much brokerage was generated from ${topScheme.substring(0, 25)}...?`,
      brokerageSummary,
      "What is the meaning of BRKAGE_RATE and AVG_ASSETS?",
      "Which scheme has the highest investment amount?",
      "What does CAM_RATE and MAM_RATE represent in simple language?",
      "Show all transactions and folios extracted from this file."
    ];

    if (hasValuation) {
      questions.push("What is the calculated profit and return percentage?");
      questions.push("Which mutual fund holding generated the highest return?");
    } else {
      questions.push("Why can't you calculate my return from this document?");
      questions.push("What additional data is required for accurate return calculation?");
    }

    questions.push("Explain this report in simple language for an investor.");
    return questions;
  }

  // Context-aware Chatbot Answer Engine
  answerQuery(query, report) {
    if (!report) {
      return "Please upload or select a document first so I can analyze its contents.";
    }

    const q = query.toLowerCase().trim();
    const summary = report.summary;
    const formatCurrency = (value) => hasNumericValue(value)
      ? `₹${Number(value).toLocaleString('en-IN')}`
      : 'Not available';
    const formatNumber = (value) => hasNumericValue(value)
      ? Number(value).toLocaleString('en-IN')
      : 'Not available';

    // Technical field explanation questions
    if (q.includes("brkage_rate") || q.includes("brokerage rate")) {
      return `**BRKAGE_RATE Explanation:**\n\n${FIELD_DEFINITIONS.BRKAGE_RATE}\n\nIn your uploaded document (**${report.docName}**), the effective average brokerage rate is **${summary.avgBrokerageRate}**.`;
    }
    if (q.includes("brkage_amt") || q.includes("brokerage amount") || q.includes("total brokerage")) {
      return `**BRKAGE_AMT Explanation:**\n\n${FIELD_DEFINITIONS.BRKAGE_AMT}\n\nTotal brokerage recorded in this document: **${formatCurrency(summary.totalBrokerage)}**.`;
    }
    if (q.includes("avg_assets") || q.includes("average asset")) {
      return `**AVG_ASSETS Explanation:**\n\n${FIELD_DEFINITIONS.AVG_ASSETS}\n\nTotal average assets in this statement: **${formatCurrency(summary.totalAssetsAnalyzed)}**.`;
    }
    if (q.includes("am_rate") || q.includes("cam_rate") || q.includes("mam_rate")) {
      return `**Component Rate Definitions:**\n\n- **AM_RATE**: ${FIELD_DEFINITIONS.AM_RATE}\n- **CAM_RATE**: ${FIELD_DEFINITIONS.CAM_RATE}\n- **MAM_RATE**: ${FIELD_DEFINITIONS.MAM_RATE}\n\nThe source does not provide additional descriptions for these components.`;
    }

    // Investment & Summary questions
    if (q.includes("total investment") || q.includes("how much did i invest") || q.includes("invested amount")) {
      return `Based on **${report.docName}**:\n\n- **Total Investment Amount**: ${formatCurrency(summary.totalInvestment)}\n- **Total Units**: ${formatNumber(summary.totalUnits)}\n- **Number of Schemes**: ${formatNumber(summary.schemesCount)}\n- **Number of Folios**: ${formatNumber(summary.foliosCount)}\n- **Period**: ${summary.period}`;
    }

    // Scheme comparison / highest investment
    if (q.includes("highest investment") || q.includes("top scheme") || q.includes("largest investment")) {
      const sorted = [...report.schemeList]
        .filter((scheme) => hasNumericValue(scheme.totalInvestment))
        .sort((a, b) => Number(b.totalInvestment) - Number(a.totalInvestment));
      const top = sorted[0];
      if (!top) return "I could not find investment amounts in the uploaded document.";
      return `**Top Scheme by Investment:**\n\n- **Scheme**: ${top.schemeName}\n- **Investment Amount**: ${formatCurrency(top.totalInvestment)}\n- **Units**: ${formatNumber(top.totalUnits)}\n- **Brokerage Generated**: ${formatCurrency(top.brokerageAmount)}`;
    }

    // Return calculations & missing data questions
    if (q.includes("return") || q.includes("profit") || q.includes("xirr") || q.includes("cagr")) {
      if (report.returnAnalysis.hasSufficientData) {
        return `**Investment Return Analysis:**\n\n- **Total Invested**: ${formatCurrency(report.returnAnalysis.totalInvested)}\n- **Current Value**: ${formatCurrency(report.returnAnalysis.totalCurrentVal)}\n- **Absolute Profit**: ${formatCurrency(report.returnAnalysis.totalProfit)}\n- **Return %**: ${report.returnAnalysis.absoluteReturn}%\n- **XIRR**: Not available\n\n*Calculation Basis*: ${report.returnAnalysis.calculationBasis}`;
      } else {
        return `**Notice regarding Return Calculation:**\n\n${report.returnAnalysis.message}\n\n*Missing Fields*: ${report.missingDataFields.join(', ')}.\nTo calculate returns, please upload a Consolidated Account Statement (CAS) or CAMS statement with current NAV and valuation values.`;
      }
    }

    // Missing information question
    if (q.includes("missing") || q.includes("why can't you calculate")) {
      if (report.missingDataFields.length === 0) {
        return "The fields checked for this analysis are present in the uploaded records.";
      } else {
        return `The following information was **not present** in the uploaded document:\n\n${report.missingDataFields.map(f => `- **${f}**`).join('\n')}\n\nAs per strict financial compliance rules, we do NOT invent or fabricate numbers without verified document records.`;
      }
    }

    // Simple language summary
    if (q.includes("simple") || q.includes("explain") || q.includes("summary")) {
      return `### Summary of ${report.docName}:\n\n1. **Document Source**: ${report.source} (${report.docType}).\n2. **Recorded Investment**: ${formatCurrency(summary.totalInvestment)} across ${formatNumber(summary.schemesCount)} schemes.\n3. **Recorded Brokerage**: ${formatCurrency(summary.totalBrokerage)} at an average source rate of ${summary.avgBrokerageRate}.\n4. **Missing fields**: ${report.missingDataFields.length ? report.missingDataFields.join(', ') : 'None of the checked fields.'}`;
    }

    // General fallback
    return `Based strictly on the extracted records in **${report.docName}**:\n\n- Total Investment: ${formatCurrency(summary.totalInvestment)}\n- Total Brokerage: ${formatCurrency(summary.totalBrokerage)}\n- Schemes Analyzed: ${formatNumber(summary.schemesCount)}\n- Source: ${report.source}\n\nIf you need specific details on a folio, scheme, or brokerage field, feel free to ask!`;
  }
}

export const agentPipeline = new AgenticPipeline();
